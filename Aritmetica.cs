namespace Calculos
{
    /// <summary>
    /// Implementa operações aritméticas básicas
    /// </summary>
    internal class Aritmetica
    {
        public int Somar(int a, int b)
        {
            return a + b;
        }

        public int Subtrair(int a, int b)
        {
            return a - b;
        }
    }
}